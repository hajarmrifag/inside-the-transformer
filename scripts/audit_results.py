"""Independently recompute reported statistics from stored per-example measurements.

Does not import the project's analysis/metric implementations or load a model.
This checks arithmetic/provenance, not whether the CSVs were generated by a model;
same-machine inference repetitions and the hook tests provide separate evidence.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT=Path(__file__).resolve().parents[1]


def bootstrap(frame,column,seed):
    groups=frame.groupby("pair")[column]
    sizes=groups.size()
    if sizes.nunique()!=1:
        raise ValueError("audit assumes equal-size clusters, as required by this design")
    values=groups.mean().to_numpy()
    draws=np.random.default_rng(seed).choice(values,(5000,len(values)),replace=True).mean(axis=1)
    low,high=np.quantile(draws,[.025,.975])
    return dict(mean=float(frame[column].mean()),low=float(low),high=float(high),n=len(frame),clusters=len(values))


def audit(original,extension):
    ledger=[]
    def compare(label,reported,actual,tol=1e-8):
        if reported is None or actual is None:
            assert reported is actual,label
            return
        error=abs(float(reported)-float(actual))
        assert np.isfinite(error) and error<=tol,(label,reported,actual,error)
        ledger.append(dict(claim=label,reported=float(reported),recomputed=float(actual),absolute_error=error,tolerance=tol))
    def compare_stats(label,reported,frame,column,seed):
        computed=bootstrap(frame,column,seed)
        for key,value in computed.items():compare(f"{label}.{key}",reported[key],value)
    def load(folder):
        d=pd.DataFrame(json.loads((folder/"dataset.json").read_text()))
        b=pd.read_csv(folder/"baselines.csv");r=pd.read_csv(folder/"interventions.csv")
        assert d.id.is_unique and b.id.is_unique and set(d.id)==set(b.id)
        assert not r[["patched_ld","gain"]].isna().any().any()
        return d,b.merge(d,on="id",validate="one_to_one"),r.merge(d,on="id",validate="many_to_one")
    d,b,r=load(original)
    assert len(d)==128 and len(r)==12288 and set(r.id)==set(d.id)
    assert not r.duplicated(["id","layer","position","kind"]).any()
    for name in ["clean","corrupted"]:
        target=b.answer if name=="clean" else b.foil
        assert b[f"{name}_top1_correct"].eq(b[f"{name}_top1_token"].eq(target)).all()
    lookup=b.set_index("id")
    ref=np.array([lookup.loc[row.id,"clean_ld" if row.kind=="clean_noop" else "corrupted_ld"] for row in r.itertuples()])
    max_error=float(np.max(np.abs(r.gain.to_numpy()-(r.patched_ld.to_numpy()-ref))))
    assert max_error<2e-6  # Original gains were subtracted in float32.
    s=json.loads((original/"summary.json").read_text());seed=20261113
    final=r[(r.kind=="clean_patch")&(r.position=="final")]
    development=final[(final.split=="dev_names")&(final.layer>=6)]
    selected=int(development.groupby("layer").gain.mean().idxmax())
    compare("original.selected_layer",s["selected_layer"],selected)
    for entry in s["splits"]:
        split=entry["split"];base=b[b.split==split]
        matched=final[(final.split==split)&(final.layer==selected)]
        unrelated=r[(r.split==split)&(r.layer==selected)&(r.kind=="unrelated_donor")]
        paired=matched.merge(unrelated[["id","gain"]],on="id",suffixes=("","_unrelated"),validate="one_to_one")
        paired["contrast"]=paired.gain-paired.gain_unrelated
        compare_stats(f"original.{split}.matched",entry,matched,"gain",seed)
        compare_stats(f"original.{split}.specificity",entry["specificity"],paired,"contrast",seed)
        for metric in ["clean_ld","corrupted_ld"]:compare_stats(f"original.{split}.{metric}",entry[metric],base,metric,seed)
        gap=float((base.clean_ld-base.corrupted_ld).mean())
        compare(f"original.{split}.gap",entry["gap"],gap)
        compare(f"original.{split}.recovery",entry["recovery"],matched.gain.mean()/gap if gap>.5 else None)
        for key,value in dict(clean_pairwise_accuracy=(base.clean_ld>0).mean(),corrupted_pairwise_accuracy=(base.corrupted_ld<0).mean(),
                              clean_top1_accuracy=base.clean_top1_correct.mean(),corrupted_top1_accuracy=base.corrupted_top1_correct.mean()).items():
            compare(f"original.{split}.{key}",entry[key],value)
    for row in pd.read_csv(original/"aggregated.csv").to_dict("records"):
        subset=r[(r.split==row["split"])&(r.layer==row["layer"])&(r.position==row["position"])&(r.kind==row["kind"])]
        compare_stats(f"original.aggregate.{row['split']}.{row['layer']}.{row['position']}.{row['kind']}",row,subset,"gain",seed)
    compare("original.max_noop_error",s["max_noop_error"],r[r.kind.isin(["clean_noop","corrupted_noop"])].gain.abs().max())
    compare("original.max_prefix_null_error",s["max_prefix_null_error"],r[r.position.isin(["bos","name1","name2"])].gain.abs().max())
    repair=r[(r.kind=="clean_patch")&(r.layer==0)&(r.position=="subject")].merge(b[["id","clean_ld"]],on="id")
    compare("original.max_embedding_repair_error",s["max_embedding_repair_error"],(repair.patched_ld-repair.clean_ld).abs().max())

    ed,eb,er=load(extension);es=json.loads((extension/"summary.json").read_text());seed=20261114
    evaluation=eb[eb.pool=="evaluation"];donors=eb[eb.pool=="donor"]
    assert len(ed)==128 and len(evaluation)==len(donors)==64 and len(er)==448
    assert er.groupby("id").kind.nunique().eq(7).all() and er.layer.eq(selected).all()
    assert not er.duplicated(["id","kind"]).any()
    old_names={name for row in d.to_dict("records") for name in [row["a"],row["b"]]}
    assert old_names.isdisjoint(set(ed["first"])|set(ed["second"]))
    assert (set(evaluation["first"])|set(evaluation["second"])).isdisjoint(set(donors["first"])|set(donors["second"]))
    assert evaluation.answer_position.value_counts().to_dict()=={1:32,2:32}
    lookup=eb.set_index("id")
    reference=np.array([lookup.loc[row.id,"clean_ld" if row.kind=="clean_noop" else "corrupted_ld"] for row in er.itertuples()])
    extension_error=float(np.max(np.abs(er.gain.to_numpy()-(er.patched_ld.to_numpy()-reference))))
    assert extension_error<1e-9
    assert er.clean_answer_top1.eq(er.top1_token.eq(er.answer)).all()
    for row in er[er.kind.str.startswith("unrelated")].itertuples():
        donor=lookup.loc[row.donor_id]
        assert donor.pool=="donor" and donor.block==row.block
        assert {row.first,row.second}.isdisjoint({donor["first"],donor["second"]})
        assert donor.answer_position==(row.answer_position if row.kind=="unrelated_same_position" else 3-row.answer_position)
    gate=json.loads((extension/"baseline_validation.json").read_text())
    for row in gate["strata"]:
        frame=eb[(eb.pool==row["pool"])&(eb.template==row["template"])&(eb.answer_position==row["answer_position"])]
        actual=dict(n=len(frame),clusters=frame.block.nunique(),clean_pairwise_accuracy=(frame.clean_ld>0).mean(),
            corrupted_pairwise_accuracy=(frame.corrupted_ld<0).mean(),clean_top1_accuracy=frame.clean_top1_correct.mean(),
            corrupted_top1_accuracy=frame.corrupted_top1_correct.mean(),mean_clean_ld=frame.clean_ld.mean(),
            mean_corrupted_ld=frame.corrupted_ld.mean(),mean_gap=(frame.clean_ld-frame.corrupted_ld).mean())
        for key,value in actual.items():compare(f"extension.baseline.{row['pool']}.t{row['template']}.p{row['answer_position']}.{key}",row[key],value)
        assert row["passed"]==bool(actual["clean_pairwise_accuracy"]>=.8 and actual["corrupted_pairwise_accuracy"]>=.8 and actual["mean_gap"]>.5)
    assert gate["all_strata_passed"]==all(x["passed"] for x in gate["strata"])
    wide=er.pivot(index="id",columns="kind",values="gain").reset_index().merge(evaluation[["id","pair"]],on="id")
    wide["unrelated_balanced"]=(wide.unrelated_same_position+wide.unrelated_opposite_position)/2
    wide["matched_minus_balanced"]=wide.matched-wide.unrelated_balanced
    wide["matched_minus_same"]=wide.matched-wide.unrelated_same_position
    wide["matched_minus_opposite"]=wide.matched-wide.unrelated_opposite_position
    wide["same_minus_opposite"]=wide.unrelated_same_position-wide.unrelated_opposite_position
    for name,reported in es["contrasts"].items():compare_stats(f"extension.{name}",reported,wide,name,seed)
    gap=float((evaluation.clean_ld-evaluation.corrupted_ld).mean())
    compare("extension.mean_baseline_gap",es["mean_baseline_gap"],gap)
    for reported in es["conditions"]:
        frame=er[er.kind==reported["kind"]]
        compare_stats(f"extension.{reported['kind']}",reported,frame,"gain",seed)
        compare(f"extension.{reported['kind']}.pairwise",reported["clean_pairwise_preference"],(frame.patched_ld>0).mean())
        compare(f"extension.{reported['kind']}.top1",reported["clean_answer_top1_accuracy"],frame.clean_answer_top1.mean())
        recovery=frame.gain.mean()/gap if gate["all_strata_passed"] and reported["kind"] in ["matched","unrelated_same_position","unrelated_opposite_position"] else None
        compare(f"extension.{reported['kind']}.recovery",reported["recovery"],recovery)
    for reported in es["matched_by_answer_position"]:
        frame=er[(er.kind=="matched")&(er.answer_position==reported["answer_position"])]
        compare_stats(f"extension.matched.position{reported['answer_position']}",reported,frame,"gain",seed)
    for entry in es["baseline_means"]:compare_stats(f"extension.baseline.{entry['metric']}",entry,evaluation,entry["metric"],seed)
    for key,value in dict(baseline_clean_pairwise_accuracy=(evaluation.clean_ld>0).mean(),baseline_corrupted_pairwise_accuracy=(evaluation.corrupted_ld<0).mean(),
        baseline_clean_top1_accuracy=evaluation.clean_top1_correct.mean(),baseline_corrupted_top1_accuracy=evaluation.corrupted_top1_correct.mean()).items():compare(f"extension.{key}",es[key],value)
    for row in pd.read_csv(extension/"aggregated.csv").to_dict("records"):
        frame=er[er.kind==row["kind"]]
        if row["group"]=="answer_position":frame=frame[frame.answer_position==int(row["label"])]
        elif row["group"]=="template_position":
            template,pos=row["label"].split("-");frame=frame[(frame.template==int(template[1:]))&(frame.answer_position==int(pos[1:]))]
        compare_stats(f"extension.aggregate.{row['group']}.{row['label']}.{row['kind']}",row,frame,"gain",seed)
        compare("extension.aggregate.pairwise",row["clean_pairwise_preference"],(frame.patched_ld>0).mean())
        compare("extension.aggregate.top1",row["clean_answer_top1_accuracy"],frame.clean_answer_top1.mean())
    null=er[er.kind.isin(["clean_noop","corrupted_noop","bos_null","name1_null"])].gain.abs().max()
    compare("extension.max_null_error",es["max_null_error"],null)
    assert null<1e-4
    failures=json.loads((extension/"failure_analysis.json").read_text()) if (extension/"failure_analysis.json").exists() else None
    if failures:
        for pool,frame in eb.groupby("pool"):
            record=failures["pools"][pool]
            compare(f"extension.failures.{pool}.pairwise",record["clean_pairwise_failures"],(frame.clean_ld<=0).sum())
            compare(f"extension.failures.{pool}.top1",record["clean_top1_failures"],(~frame.clean_top1_correct).sum())
            assert record["wrong_clean_top1_tokens"]==frame.loc[~frame.clean_top1_correct,"clean_top1_text"].value_counts().to_dict()
        compare("extension.matched_patch_failures",len(failures["matched_patch_failures"]),len(er[(er.kind=="matched")&(er.patched_ld<=0)]))
    before_hashes=0
    for folder in [original,extension]:
        for name,digest in json.loads((folder/"artifact_hashes.json").read_text()).items():
            assert hashlib.sha256((folder/name).read_bytes()).hexdigest()==digest,(folder.name,name)
            before_hashes+=1
    return dict(passed=True,fields_recomputed=len(ledger),artifact_hashes_checked=before_hashes,
        original_n=128,original_interventions=12288,extension_evaluation_n=64,extension_donor_n=64,extension_interventions=448,
        original_gain_subtraction_max_error=max_error,extension_gain_subtraction_max_error=extension_error,
        bootstrap_repeats=5000,extension_blocks=8,bootstrap_intervals_are_conditional=True),ledger


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--original",type=Path,default=ROOT/"results")
    parser.add_argument("--extension",type=Path,default=ROOT/"results/counterbalanced-v1")
    parser.add_argument("--output",type=Path,default=ROOT/"audit/numeric-audit.json")
    args=parser.parse_args();summary,ledger=audit(args.original,args.extension)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(summary,indent=2)+"\n")
    pd.DataFrame(ledger).to_csv(args.output.with_suffix(".csv"),index=False)
    print(json.dumps(summary,indent=2))


if __name__=="__main__":main()
